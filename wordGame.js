/**
 * Randomly scramble a word ensuring it does not equal the original word.
 */
export function scrambleWord(word) {
  const upper = word.toUpperCase();
  const letters = upper.split("");
  if (letters.length <= 1) return upper;

  for (let attempt = 0; attempt < 100; attempt++) {
    const shuffled = [...letters];
    for (let i = shuffled.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    const result = shuffled.join("");
    if (result !== upper) {
      return result;
    }
  }

  // Fallback swap if random shuffle stayed the same
  const fallback = [...letters];
  for (let i = 0; i < fallback.length - 1; i++) {
    if (fallback[i] !== fallback[i + 1]) {
      [fallback[i], fallback[i + 1]] = [fallback[i + 1], fallback[i]];
      break;
    }
  }
  return fallback.join("");
}

/**
 * Generate Wordle-style boxes comparing the scrambled clue to the target word:
 * 🟩 = Correct letter & correct position
 * 🟨 = Correct letter & wrong position
 */
export function generateBoxes(targetWord, scrambledWord) {
  const target = targetWord.toUpperCase();
  const scrambled = scrambledWord.toUpperCase();
  const len = target.length;
  const resultBoxes = new Array(len).fill("🟨");

  // Count available letters for yellow assignment
  const letterCounts = {};
  for (let i = 0; i < len; i++) {
    const char = target[i];
    letterCounts[char] = (letterCounts[char] || 0) + 1;
  }

  // Pass 1: Mark Exact matches (Green)
  for (let i = 0; i < len; i++) {
    if (scrambled[i] === target[i]) {
      resultBoxes[i] = "🟩";
      letterCounts[scrambled[i]]--;
    }
  }

  // Pass 2: Remaining letters (Yellow or Black/Gray)
  for (let i = 0; i < len; i++) {
    if (resultBoxes[i] === "🟩") continue;

    const char = scrambled[i];
    if (letterCounts[char] && letterCounts[char] > 0) {
      resultBoxes[i] = "🟨";
      letterCounts[char]--;
    } else {
      resultBoxes[i] = "⬛";
    }
  }

  return resultBoxes;
}

/**
 * Format the scrambled word with letter spacing and matching box row
 */
export function formatPuzzleBoard(scrambledWord, boxes) {
  const upper = scrambledWord.toUpperCase();
  const boxRow = boxes.join(" ");
  const letterRow = upper.split("").join("  ");

  return { boxRow, letterRow };
}

/**
 * Pick a random word from the list
 */
export function getRandomPuzzleWord() {
  const index = Math.floor(Math.random() * famousWords.length);
  return famousWords[index].toUpperCase();
}

